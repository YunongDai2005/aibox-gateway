// 给工人（DSH）的固定话术。改这里的措辞会影响模型行为，改前先跑 test/。

// 主人在工人干活途中插话：沿用已有上下文和成果按新要求调整，不从头重做
export function wrapSteer(userText) {
  return '[用户在你执行任务的过程中插话]\n'
    + '用户原话：' + userText + '\n'
    + '先判断这句跟**你手上正在做的任务**是什么关系：\n'
    + '· 是补充/修改/纠正/追问这件任务 → 沿用你已经掌握的上下文和工作目录里已经产出的成果，'
    + '按这条要求调整做法继续做，**不要从头重做已经做完的部分**。\n'
    + '· 是另一件不相干的事 → 先用一两句简短回应它，**然后把原来的任务继续做完**，别把原任务丢掉。\n'
    + '无论哪种，只输出最终结果，不要解释你的判断过程。';
}

// 工人这一轮结束后，信箱里还有它没看的留言 → 作为下一条消息补交
export function mailboxDelivery(body) {
  return '【你刚才干活时主人说的话（经理转达，你还没看到）】\n' + body + '\n请现在处理：需要调整刚交付的就调整，需要回答就回答。';
}
